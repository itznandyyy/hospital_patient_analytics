-- 14. Patients whose Treatment Cost is greater than the average Treatment Cost of their department.
select h.PatientID, h.Department, h.TreatmentCost
from hospitaldata h
where h.TreatmentCost > (
    select avg(h2.TreatmentCost)
    from hospitaldata h2
    where h2.Department = h.Department
)
order by  h.Department, h.TreatmentCost desc;

-- 15. Which departments have a readmission rate above the hospital average?
with dept_rate as (
    select Department,
           count(*) as Patients,
           round(100.0 * sum(Readmitted30Days = 'Yes') / count(*), 2) as ReadmissionRatePct
    from hospitaldata
    group by Department
)
select Department,
       Patients,
       ReadmissionRatePct,
       round((select 100.0 * sum(Readmitted30Days = 'Yes') / count(*) from hospitaldata), 2) as HospitalavgPct,
       rank() over (order by ReadmissionRatePct desc) as Riskrank
from dept_rate
order by Riskrank;

-- 16. Patient profile by age group
select case
           when Age < 18 then '1. Child (0-17)'
           when Age between 18 and 39 then '2. Young adult (18-39)'
           when Age between 40 and 59 then '3. Middle age (40-59)'
           else '4. Senior (60+)'
       end as AgeGroup,
       count(*) as Patients,
       round(avg(TotalBill), 2) as avgBill,
       round(avg(LengthOfStay_Days), 2) as avgStayDays,
       round(100.0 * sum(Readmitted30Days = 'Yes') / count(*), 2) as ReadmissionRatePct
from hospitaldata
group by AgeGroup
order by AgeGroup;

-- 17. Does waiting longer make patients less satisfied?
select case
           when WaitingTime_Min < 30 then '1. Under 30 min'
           when WaitingTime_Min < 60 then '2. 30-59 min'
           when WaitingTime_Min < 120 then '3. 60-119 min'
           else '4. 120+ min'
       end as WaitBand,
       count(*) as Patients,
       round(avg(PatientSatisfaction), 2) as avgSatisfaction
from hospitaldata
group by WaitBand
order by WaitBand;

-- 18. Monthly revenue with month-over-month change and running total
with monthly as (
    select DATE_ForMAT(VisitDate, '%Y-%m') as Month,
           count(*) as Visits,
           round(sum(TotalBill), 2) as Revenue
    from hospitaldata
    group by DATE_ForMAT(VisitDate, '%Y-%m')
)
select Month,
       Visits,
       Revenue,
       round(100.0 * (Revenue - lag(Revenue) over (order by Month))
                 / lag(Revenue) over (order by Month), 2) as MoM_ChangePct,
       round(sum(Revenue) over (order by Month), 2) as RunningRevenue
from monthly
order by Month;
-- January has no previous month, so MoM change is NULL.

-- 19. Top 3 highest-billing patients inside each department
select Department, PatientID, City, TotalBill, BillrankInDept
from (
    select Department, PatientID, City, TotalBill,
           row_number() over (partition by Department order by TotalBill desc) as BillrankInDept
    from hospitaldata
) ranked
where BillrankInDept <= 3
order by Department, BillrankInDept;

-- 20. Priority departments: slower than average and readmitting above average
with dept as (
    select Department,
           avg(WaitingTime_Min) as avgWait,
           100.0 * sum(Readmitted30Days = 'Yes') / count(*) as ReadmitPct,
           avg(PatientSatisfaction) as avgSat
    from hospitaldata
    group by Department
),
overall as (
    select avg(WaitingTime_Min) as WaitAll,
           100.0 * sum(Readmitted30Days = 'Yes') / count(*) as ReadmitAll
    from hospitaldata
)
select d.Department,
       round(d.avgWait, 2) as avgWaitMin,
       round(d.ReadmitPct, 2) as ReadmissionPct,
       round(d.avgSat, 2) as avgSatisfaction,
       case
           when d.avgWait > o.WaitAll and d.ReadmitPct > o.ReadmitAll then 'High priority'
           when d.avgWait > o.WaitAll or d.ReadmitPct > o.ReadmitAll then 'Watch'
           else 'On track'
       end as PriorityFlag
from dept d
cross join overall o
order by d.avgWait desc;

-- 21. Doctor workload and performance
select Doctor,
       count(*) as Patients,
       round(100.0 * count(*) / sum(count(*)) over (), 2) as SharePct,
       round(avg(WaitingTime_Min), 2) as avgWaitMin,
       round(avg(PatientSatisfaction), 2) as avgSatisfaction,
       rank() over (order by count(*) desc) as Workloadrank
from hospitaldata
group by Doctor
order by Workloadrank;

-- 22. Revenue concentration by department (Pareto view)
with dept_rev as (
    select Department, sum(TotalBill) as Revenue
    from hospitaldata
    group by Department
)
select Department,
       round(Revenue, 2) as Revenue,
       round(100.0 * Revenue / sum(Revenue) over (), 2) as SharePct,
       round(100.0 * sum(Revenue) over (order by Revenue desc) / sum(Revenue) over (), 2) as CumulativeSharePct
from dept_rev
order by Revenue desc;







